import { coreBaseUrl, coreFetch } from '../packages/domain/core-http.ts';
import { readFile } from 'node:fs/promises';
import { randomUUID } from 'node:crypto';
import assert from 'node:assert/strict';
import { pool } from '../packages/storage/db.ts';
const base=coreBaseUrl(process.env.CORE_URL??'http://127.0.0.1:3000');
const owner=(await readFile(process.env.OWNER_TOKEN_FILE??'secrets/owner_token','utf8')).trim();
const audio=(await readFile(process.env.AUDIO_TOKEN_FILE??'secrets/audio_token','utf8')).trim();
async function req(path:string,token:string,body?:unknown,expected=200){
 const r=await coreFetch(base+path,{method:body?'POST':'GET',headers:{Authorization:`Bearer ${token}`,'Content-Type':'application/json'},body:body?JSON.stringify(body):undefined});
 assert.equal(r.status,expected,path);return r.json();
}
await req('/owner/resume',owner,{});
assert.equal((await req('/audio/claim',audio,{})).job,null);
await req('/owner/status',audio,undefined,401);
await req('/audio/claim',owner,{},401);
const body={request_id:randomUUID(),text:'Synthetic speech smoke. Do not play.'};
const first=await req('/owner/speech',owner,body);
assert.equal((await req('/owner/speech',owner,body)).id,first.id);
await req('/owner/speech',owner,{...body,text:'conflict'},409);
const claim=(await req('/audio/claim',audio,{})).job;
assert.equal(claim.id,first.id);
assert.equal((await req('/audio/claim',audio,{})).job,null);
await req(`/audio/jobs/${claim.id}`,audio,{claim_id:randomUUID(),state:'playing'},409);
await req(`/audio/jobs/${claim.id}`,audio,{claim_id:claim.claim_id,state:'completed'},409);
await req(`/audio/jobs/${claim.id}`,audio,{claim_id:claim.claim_id,state:'playing'});
await req('/owner/pause',owner,{});
assert.equal((await req(`/audio/jobs/${claim.id}`,audio)).allowed,false);
assert.equal((await req(`/audio/jobs/${claim.id}`,audio,{claim_id:claim.claim_id,state:'completed'})).state,'cancelled');
await req('/owner/resume',owner,{});
const pending=await req('/owner/speech',owner,{request_id:randomUUID(),text:'Cancel pending'});
assert.equal((await req(`/owner/speech/${pending.id}/cancel`,owner,{})).state,'cancelled');
assert.equal((await req('/audio/claim',audio,{})).job,null);
for(let i=0;i<3;i++)await req('/owner/speech',owner,{request_id:randomUUID(),text:`Bounded queue ${i}`});
await req('/owner/speech',owner,{request_id:randomUUID(),text:'Queue overflow'},409);
const uncertain=(await req('/audio/claim',audio,{})).job;
await pool.query("UPDATE speech_jobs SET expires_at=now()-interval '1 second' WHERE id=$1",[uncertain.id]);
const following=(await req('/audio/claim',audio,{})).job;
assert.notEqual(following.id,uncertain.id,'Expired claimed speech is never replayed');
assert.equal((await req(`/owner/speech/${uncertain.id}`,owner)).state,'unknown');
await req('/owner/pause',owner,{});
assert.equal((await req('/audio/claim',audio,{})).job,null);
await req('/owner/resume',owner,{});
await pool.end();
console.log('Speech queue smoke passed. No playback.');
